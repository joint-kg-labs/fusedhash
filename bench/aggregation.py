#!/usr/bin/env python3
"""Monotonic aggregation: CC and SSSP (mmin) and company control (msum with threshold),
FusedHash against SortMerge (our CUDA extension of the sort-based design of FVlog, which has no
aggregates; Souffle does not allow recursion through aggregates).

  python3 bench/aggregation.py [--only cc sssp ctrl] [--datasets RMAT-20 ...] [--resume]
      -> results/aggregation.csv

Inputs: data/agg/<name>.bin (generated by data/prepare.py with the generators of data/datasets.py).
Result: groups and checksum (sum of the values) for CC/SSSP; control facts and groups of the
running sums for company control. Both engines must agree.
"""
import argparse, json, os
import harness as H

GRAPHS = ["RMAT-20", "RMAT-22", "RMAT-24", "Grid250", "Grid500", "Grid1000", "Grid2000",
          "Sym-usroads", "Sym-fe_ocean", "Sym-road_usa", "Sym-europe_osm",
          "SW-1e-4", "SW-1e-3", "SW-1e-2", "SW-1e-1"]
SUITE = {"cc": GRAPHS, "sssp": GRAPHS,
         "ctrl": ["Own-1M", "Own-2M", "Own-4M", "Own-8M", "Own-16M", "Own-32M", "Own-64M", "PSC"]}
FIELDS = ["program", "dataset", "rows", "result", "checksum", "iters_hash", "iters_sort", "map_keys",
          "fusedhash_s", "sortmerge_s", "agree", "notes"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", default=list(SUITE))
    ap.add_argument("--datasets", nargs="*")
    ap.add_argument("--resume", action="store_true")
    a = ap.parse_args()
    out = H.Csv("aggregation.csv", FIELDS, a.resume)
    for prog in a.only:
        for name in SUITE[prog]:
            if (a.datasets and name not in a.datasets) or (prog, name) in out.done:
                continue
            path = os.path.join(H.DATA, "agg", f"{name}.bin")
            if not os.path.exists(path):
                print(f"{prog:4s} {name:15s} skipped: no input (data/prepare.py; PSC needs data/psc.py)")
                continue
            meta = json.load(open(os.path.join(H.DATA, "agg", f"{name}.json")))
            args = dict(prog=prog, input=path, source=meta["source"])
            fh = H.engine("fusedhash_agg", **args)
            sm = H.engine("sortmerge_agg", **args)
            same = not (fh.ok and sm.ok) or (fh.data["result"] == sm.data["result"] and
                                              (prog == "ctrl" or fh.data["checksum"] == sm.data["checksum"]))
            ref = fh if fh.ok else sm
            print(f"{prog:4s} {name:15s} {ref.data.get('result', '')!s:>12}  hash {fh.cell()} "
                  f"({fh.data.get('iters', '')} it)  sort {sm.cell()} ({sm.data.get('iters', '')} it)  "
                  f"{'' if same else 'MISMATCH'}", flush=True)
            out.row(program=prog, dataset=name, rows=meta["rows"], result=ref.data.get("result", ""),
                    checksum=ref.data.get("checksum", ""), iters_hash=fh.data.get("iters", ""),
                    iters_sort=sm.data.get("iters", ""), map_keys=ref.data.get("map_keys", ""),
                    fusedhash_s=fh.cell(), sortmerge_s=sm.cell(), agree=int(same),
                    notes="; ".join(f"{n}: {o.message}" for n, o in (("fusedhash", fh), ("sortmerge", sm))
                                    if o.kind == "error"))


if __name__ == "__main__":
    main()
